def plot_cumulative_transfer(df, output_dir):
    """Plots cumulative transferred data (UP and DOWN) over time."""
    df_transfer = df[df["event"] == "transfer"].copy()
    if df_transfer.empty:
        click.echo("No transfer events found for cumulative plot.")
        return

    files = sort_files_by_conn(df_transfer["file"].unique())
    plt.figure(figsize=(12, 6))
    for f in files:
        df_file = df_transfer[df_transfer["file"] == f].sort_values("timestamp")
        df_file = df_file.dropna(subset=["up_mb", "down_mb"])
        if df_file.empty:
            continue
        cum_up = df_file["up_mb"].cumsum()
        cum_down = df_file["down_mb"].cumsum()
        mode = "baseline" if "baseline" in f.lower() else "benchmark"
        if mode == "baseline":
            up_style = {"linestyle": "--", "marker": "o"}
            down_style = {"linestyle": "--", "marker": "x"}
        else:
            up_style = {"linestyle": "-", "marker": "o"}
            down_style = {"linestyle": "-", "marker": "x"}

        plt.plot(df_file["timestamp"], cum_up, label=f"{f} UP cumulative", **up_style)
        plt.plot(
            df_file["timestamp"], cum_down, label=f"{f} DOWN cumulative", **down_style
        )
    plt.xlabel("Timestamp")
    plt.ylabel("Cumulative Data Transferred (MB)")
    plt.title("Cumulative Data Transfer Over Time")
    plt.legend(fontsize="small", loc="upper left")
    plt.grid(True)
    plt.tight_layout()
    output_file = os.path.join(output_dir, "cumulative_transfer.png")
    plt.savefig(output_file)
    click.echo(f"Cumulative transfer plot saved as {output_file}")
    plt.close()


def plot_aggregated_bar_chart(df, output_dir):
    """Plots aggregated bar charts of UP and DOWN average speeds by configuration."""
    df_transfer = df[df["event"] == "transfer"].copy()
    if df_transfer.empty:
        click.echo("No transfer events found for aggregated bar chart.")
        return

    df_transfer["config"] = (
        df_transfer["mode"]
        + "_"
        + df_transfer["concurrency"]
        + "_"
        + df_transfer["transfersize"]
    )
    grouped = df_transfer.groupby("config").agg(
        {"up_avg": ["mean", "std"], "down_avg": ["mean", "std"]}
    )
    grouped.columns = ["_".join(col) for col in grouped.columns]
    grouped = grouped.reset_index()

    # UP bar chart.
    plt.figure(figsize=(12, 6))
    plt.bar(
        grouped["config"], grouped["up_avg_mean"], yerr=grouped["up_avg_std"], capsize=5
    )
    plt.xlabel("Test Configuration")
    plt.ylabel("UP Avg Speed (MB/s)")
    plt.title("Average UP Speeds by Configuration with Error Bars")
    plt.xticks(rotation=45)
    plt.tight_layout()
    output_file = os.path.join(output_dir, "aggregated_up_bar_chart.png")
    plt.savefig(output_file)
    click.echo(f"Aggregated UP bar chart saved as {output_file}")
    plt.close()

    # DOWN bar chart.
    plt.figure(figsize=(12, 6))
    plt.bar(
        grouped["config"],
        grouped["down_avg_mean"],
        yerr=grouped["down_avg_std"],
        capsize=5,
    )
    plt.xlabel("Test Configuration")
    plt.ylabel("DOWN Avg Speed (MB/s)")
    plt.title("Average DOWN Speeds by Configuration with Error Bars")
    plt.xticks(rotation=45)
    plt.tight_layout()
    output_file = os.path.join(output_dir, "aggregated_down_bar_chart.png")
